/* Builds src/components/lore/mascotOutline.ts: a smoothed silhouette per pose, used for the light-theme outline.
   The traced art is wobbly at pixel scale, so we flatten each outer shape, resample it, and smooth it.
   Run: node scripts/mascot-outline.js */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'src', 'components', 'lore');
const src = fs.readFileSync(path.join(root, 'mascotArt.ts'), 'utf8');
const art = JSON.parse(src.slice(src.indexOf('{"crawl"'), src.lastIndexOf('}') + 1).replace(/;\s*$/, ''));

const STEP = 1.5;
const SIGMA = 3.5; // in samples
const MIN_AREA = 0.0012; // fraction of the canvas; drops specks and highlights
const OUTLINED = new Set(['#FAFAFA', '#E84046', '#A5BEEB', '#8CE2EC']);

function flatten(d) {
  const polys = [];
  let cur = null;
  let p = [0, 0];
  const t = d.match(/[MCLZ]|-?\d*\.?\d+/g);
  for (let i = 0; i < t.length; ) {
    const c = t[i++];
    if (c === 'M') { cur = []; polys.push(cur); p = [+t[i++], +t[i++]]; cur.push(p); }
    else if (c === 'L') { p = [+t[i++], +t[i++]]; cur.push(p); }
    else if (c === 'C') {
      const a = [+t[i++], +t[i++]], b = [+t[i++], +t[i++]], e = [+t[i++], +t[i++]];
      for (let k = 1; k <= 8; k++) {
        const u = k / 8, v = 1 - u;
        cur.push([
          v * v * v * p[0] + 3 * v * v * u * a[0] + 3 * v * u * u * b[0] + u * u * u * e[0],
          v * v * v * p[1] + 3 * v * v * u * a[1] + 3 * v * u * u * b[1] + u * u * u * e[1],
        ]);
      }
      p = e;
    }
  }
  return polys;
}

const area = (q) => { let s = 0; for (let i = 0; i < q.length; i++) { const a = q[i], b = q[(i + 1) % q.length]; s += a[0] * b[1] - b[0] * a[1]; } return Math.abs(s) / 2; };
const inside = (pt, q) => { let c = false; for (let i = 0, j = q.length - 1; i < q.length; j = i++) if ((q[i][1] > pt[1]) !== (q[j][1] > pt[1]) && pt[0] < ((q[j][0] - q[i][0]) * (pt[1] - q[i][1])) / (q[j][1] - q[i][1]) + q[i][0]) c = !c; return c; };

function resample(q) {
  const pts = [...q, q[0]];
  const out = [pts[0]];
  let need = STEP;
  for (let i = 0; i < pts.length - 1; i++) {
    let [x0, y0] = pts[i];
    const [x1, y1] = pts[i + 1];
    let len = Math.hypot(x1 - x0, y1 - y0);
    while (len >= need) {
      const f = need / len;
      x0 += (x1 - x0) * f; y0 += (y1 - y0) * f;
      out.push([x0, y0]);
      len -= need; need = STEP;
    }
    need -= len;
  }
  return out;
}

function smooth(q) {
  const r = Math.ceil(SIGMA * 3);
  const w = []; let sum = 0;
  for (let k = -r; k <= r; k++) { const v = Math.exp(-(k * k) / (2 * SIGMA * SIGMA)); w.push(v); sum += v; }
  const n = q.length;
  return q.map((_, i) => {
    let x = 0, y = 0;
    for (let k = -r; k <= r; k++) { const pt = q[(i + k + n * 10) % n]; x += pt[0] * w[k + r]; y += pt[1] * w[k + r]; }
    return [x / sum, y / sum];
  });
}

function rdp(q, eps) {
  if (q.length < 3) return q;
  const [a, b] = [q[0], q[q.length - 1]];
  let md = 0, mi = 0;
  for (let i = 1; i < q.length - 1; i++) {
    const d = Math.abs((b[0] - a[0]) * (a[1] - q[i][1]) - (a[0] - q[i][0]) * (b[1] - a[1])) / (Math.hypot(b[0] - a[0], b[1] - a[1]) || 1);
    if (d > md) { md = d; mi = i; }
  }
  if (md <= eps) return [a, b];
  return [...rdp(q.slice(0, mi + 1), eps).slice(0, -1), ...rdp(q.slice(mi), eps)];
}

const out = {};
for (const [pose, a] of Object.entries(art)) {
  const d = [];
  const all = a.layers.flatMap((l) => (OUTLINED.has(l.fill) ? flatten(l.d).map((q) => ({ q, fill: l.fill })) : []));
  for (const layer of a.layers) {
    if (!OUTLINED.has(layer.fill)) continue;
    const polys = flatten(layer.d).filter((q) => q.length > 3);
    if (process.env.DBG) console.log(pose, layer.fill, polys.map((q) => Math.round(area(q))));
    for (const q of polys) {
      if (area(q) < MIN_AREA * a.width * a.height) continue;
      // Holes (lenses, gaps) sit inside another shape of the same layer; the line-work already draws those.
      if (polys.some((o) => o !== q && area(o) > area(q) && inside(q[0], o))) continue;
      // Highlights drawn on top of another colour (the hat's shine) are not outlined.
      if (all.some((o) => o.fill !== layer.fill && area(o.q) > area(q) && inside(q[0], o.q))) continue;
      const s = smooth(resample(q));
      const h = s.length >> 1;
      const loop = [...rdp(s.slice(0, h + 1), 0.06).slice(0, -1), ...rdp([...s.slice(h), s[0]], 0.06).slice(0, -1)];
      d.push('M' + loop.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z');
    }
  }
  out[pose] = d.join('');
}

fs.writeFileSync(
  path.join(root, 'mascotOutline.ts'),
  `/* Generated by scripts/mascot-outline.js from mascotArt.ts. Do not edit by hand. */\nexport const MASCOT_OUTLINE: Record<string, string> = ${JSON.stringify(out)};\n`,
);
